function t(key, params) {
  var dictionary = I18N[currentLocale] || I18N[DEFAULT_LOCALE];
  var template = dictionary[key] || I18N[DEFAULT_LOCALE][key] || key;
  params = params || {};
  return template.replace(/\{(\w+)\}/g, function (_, name) {
    return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : "";
  });
}

function normalizeLocale(value) {
  var lang = String(value || "").toLowerCase();
  if (lang.indexOf("ja") === 0) return "ja";
  if (lang.indexOf("ko") === 0) return "ko";
  if (lang.indexOf("en") === 0) return "en";
  return "zh-CN";
}

function getUrlModeGuide(mode) {
  var suffix = mode === "contains" ? "Contains" : (mode === "regex" ? "Regex" : "Exact");
  return {
    hint: t("urlHint" + suffix),
    example: t("urlExample" + suffix)
  };
}

function getRewriteModeGuide(mode) {
  var suffix = mode === "json-merge"
    ? "JsonMerge"
    : (mode === "script" ? "Script" : (mode === "mock-fetch" ? "MockFetch" : "Replace"));
  return {
    hint: t("rewriteHint" + suffix),
    example: t("rewriteExample" + suffix)
  };
}
